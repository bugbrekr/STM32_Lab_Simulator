import { describe, it, expect } from 'vitest';
import { defaultConfig, assignSignal, setTimerClockSource, setUsart2Mode, MxConfig } from '../src/cubemx/model';
import { newProjectFromConfig, buildProject, regenerate } from '../src/project/project';
import { mergeUserCode } from '../src/cubemx/codegen';
import { Simulator } from '../src/sim/simulator';

const CLOCK_84: MxConfig['clock'] = { hseMode: 'Disable', pllSource: 'HSI', sysclkSource: 'PLLCLK', m: 8, n: 84, p: 2, q: 4, ahb: 1, apb1: 2, apb2: 1 };

function withUserCode(src: string, blocks: Record<string, string>) {
  let s = src;
  for (const [name, code] of Object.entries(blocks)) {
    const re = new RegExp(`(/\\* USER CODE BEGIN ${name} \\*/)([\\s\\S]*?)(/\\* USER CODE END ${name} \\*/)`);
    if (!re.test(s)) throw new Error('no block ' + name);
    s = s.replace(re, `$1\n${code}$2$3`);
  }
  return s;
}

function boot(cfg: MxConfig, blocks: Record<string, string>) {
  const p = newProjectFromConfig(cfg);
  p.files['Core/Src/main.c'] = withUserCode(p.files['Core/Src/main.c'], blocks);
  const r = buildProject(p);
  if (!r.ok) throw new Error(r.diags.map((d) => `${d.file}:${d.line}: ${d.message}`).join('\n'));
  const sim = new Simulator();
  sim.load(r.program!);
  return { sim, p };
}

describe('interrupt-driven code generated by CubeMX', () => {
  it('EXTI: SW1 (PB13) rising-edge interrupt toggles LED1', () => {
    let c = defaultConfig('ExtiTest');
    c.clock = { ...CLOCK_84 };
    c = assignSignal(c, 'PB13', 'GPIO_EXTI13');
    c.pins.PB13.extiMode = 'GPIO_MODE_IT_RISING';
    c = assignSignal(c, 'PB7', 'GPIO_Output');
    c.extiNvic.EXTI15_10_IRQn = true;
    const { sim, p } = boot(c, {
      '0': 'volatile int presses = 0;',
      '4': 'void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin) { if (GPIO_Pin == GPIO_PIN_13) { presses++; HAL_GPIO_TogglePin(GPIOB, GPIO_PIN_7); } }',
    });
    expect(p.files['Core/Src/stm32f4xx_it.c']).toContain('void EXTI15_10_IRQHandler(void)');
    sim.runFor(0.05);
    expect(sim.snapshot().board.leds.LED1).toBe(0);
    for (let i = 0; i < 3; i++) {
      sim.setInputs({ sw1: true });
      sim.runFor(0.02);
      sim.setInputs({ sw1: false });
      sim.runFor(0.02);
    }
    expect(sim.evalExpr('presses').value).toBe('3');
    expect(sim.snapshot().board.leds.LED1).toBe(1);
  });

  it('TIM2 update interrupt toggles LD2 every 250 ms', () => {
    let c = defaultConfig('TimIrq');
    c.clock = { ...CLOCK_84 };
    c = setTimerClockSource(c, 'TIM2', 'Internal Clock');
    c.tims.TIM2.prescaler = '8400-1';
    c.tims.TIM2.period = '2500-1';
    c.tims.TIM2.nvic = true;
    c = assignSignal(c, 'PA5', 'GPIO_Output');
    const { sim, p } = boot(c, {
      '0': 'volatile uint32_t ticks;',
      '2': '  HAL_TIM_Base_Start_IT(&htim2);',
      '4': 'void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim) { if (htim->Instance == TIM2) { ticks++; HAL_GPIO_TogglePin(GPIOA, GPIO_PIN_5); } }',
    });
    expect(p.files['Core/Src/stm32f4xx_it.c']).toContain('HAL_TIM_IRQHandler(&htim2);');
    sim.runFor(1.01);
    expect(sim.evalExpr('ticks').value).toBe('4');
  });

  it('UART receive interrupt echoes characters', () => {
    let c = defaultConfig('Echo');
    c.clock = { ...CLOCK_84 };
    c = setUsart2Mode(c, 'Asynchronous');
    c.usart2.nvic = true;
    const { sim } = boot(c, {
      '0': 'uint8_t rx;',
      '2': '  HAL_UART_Receive_IT(&huart2, &rx, 1);',
      '4': 'void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart) { uint8_t c = rx + 1; HAL_UART_Transmit(huart, &c, 1, 10); HAL_UART_Receive_IT(huart, &rx, 1); }',
    });
    sim.runFor(0.01);
    sim.uartInput([...'HAL'].map((ch) => ch.charCodeAt(0)));
    sim.runFor(0.05);
    expect(sim.mcu.uartOut.map((b) => String.fromCharCode(b.byte)).join('')).toBe('IBM');
  });

  it('missing redirect: printf output is discarded with a warning', () => {
    let c = defaultConfig('NoRedirect');
    c = setUsart2Mode(c, 'Asynchronous');
    const { sim } = boot(c, { '3': '    printf("hello\\n"); HAL_Delay(100);', Includes: '#include <stdio.h>' });
    sim.runFor(0.3);
    expect(sim.mcu.uartOut.length).toBe(0);
    expect(sim.snapshot().warnings.some((w) => w.includes('__io_putchar'))).toBe(true);
  });

  it('forgetting the GPIO clock leaves the LED dark and warns', () => {
    let c = defaultConfig('NoClock');
    c = assignSignal(c, 'PB7', 'GPIO_Output');
    const p = newProjectFromConfig(c);
    p.files['Core/Src/main.c'] = p.files['Core/Src/main.c'].replace('__HAL_RCC_GPIOB_CLK_ENABLE();', '');
    p.files['Core/Src/main.c'] = withUserCode(p.files['Core/Src/main.c'], { '3': '    HAL_GPIO_WritePin(GPIOB, GPIO_PIN_7, GPIO_PIN_SET);' });
    const r = buildProject(p);
    expect(r.ok).toBe(true);
    const sim = new Simulator();
    sim.load(r.program!);
    sim.runFor(0.05);
    const snap = sim.snapshot();
    expect(snap.board.leds.LED1).toBe(0);
    expect(snap.warnings.some((w) => w.includes('GPIOB clock is not enabled'))).toBe(true);
  });

  it('regenerating keeps USER CODE and applies the new configuration', () => {
    let c = defaultConfig('Regen');
    c = assignSignal(c, 'PB7', 'GPIO_Output');
    let p = newProjectFromConfig(c);
    p.files['Core/Src/main.c'] = withUserCode(p.files['Core/Src/main.c'], { '3': '    HAL_GPIO_TogglePin(GPIOB, GPIO_PIN_7); HAL_Delay(100);' });
    const c2 = assignSignal(c, 'PC14', 'GPIO_Output');
    p = regenerate(p, c2);
    expect(p.files['Core/Src/main.c']).toContain('HAL_GPIO_TogglePin(GPIOB, GPIO_PIN_7); HAL_Delay(100);');
    expect(p.files['Core/Src/main.c']).toContain('GPIO_PIN_14');
    expect(mergeUserCode('/* USER CODE BEGIN 1 */\n/* USER CODE END 1 */', '/* USER CODE BEGIN 1 */x/* USER CODE END 1 */')).toBe('/* USER CODE BEGIN 1 */x/* USER CODE END 1 */');
    expect(buildProject(p).ok).toBe(true);
  });

  it('HardFault on NULL pointer write is reported with the source line', () => {
    const c = defaultConfig('Fault');
    const { sim } = boot(c, { '2': '  volatile uint32_t *p = 0;\n  *p = 5;' });
    sim.runFor(0.01);
    expect(sim.status).toBe('fault');
    expect(sim.statusText).toMatch(/NULL pointer write/);
    expect(sim.faultLoc?.file).toBe('Core/Src/main.c');
  });
});
